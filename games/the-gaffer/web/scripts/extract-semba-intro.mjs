// Copies the Semba Studios intro (logo, soundtrack, styles, animation) out of Tier One's single-file build, so The Gaffer
// plays the exact same intro. Run from games/the-gaffer/web:  node scripts/extract-semba-intro.mjs
// Writes src/boot/assets.ts (logo + mp3 as base64 strings), src/boot/boot.css and src/boot/intro.ts (the animation, verbatim).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = readFileSync(resolve(here, '../../../../tier-one/index.html'), 'utf8');
const out = resolve(here, '../src/boot');

const pick = (re, what) => { const m = src.match(re); if (!m) throw new Error(`Tier One intro: ${what} not found`); return m; };
const logo = pick(/\n var LOGO='(data:image\/webp;base64,[A-Za-z0-9+/=]+)';/, 'LOGO')[1];
const snd = pick(/\n var BOOT_SND='([A-Za-z0-9+/=]+)';/, 'BOOT_SND')[1];
writeFileSync(resolve(out, 'assets.ts'),
  '// Generated by scripts/extract-semba-intro.mjs from tier-one/index.html. Do not edit by hand.\n' +
  '// The Semba Studios logo (design #17 "Neon Ring", webp) and the intro soundtrack (mp3).\n' +
  `export const LOGO = '${logo}';\nexport const BOOT_SND = '${snd}';\n`);

// Styles: every #boot rule and its two keyframes, as Tier One has them.
const css = src.split('\n').filter((l) => /^#boot[\s.:{]|^@keyframes boot(Out|Zoom)/.test(l));
if (css.length < 10) throw new Error('Tier One intro: CSS not found');
writeFileSync(resolve(out, 'boot.css'), '/* Generated by scripts/extract-semba-intro.mjs from tier-one/index.html (Semba intro, fixed brand colours). */\n' + css.join('\n') + '\n');

// Markup and the animation script: from the IIFE after <div id="boot"> to its closing "})();".
const markup = pick(/<div id="boot" aria-label="Semba Studios">\n([^\n]+)\n<\/div>/, 'markup')[1].trim();
const body = pick(/\n<script>\n(\/\* Semba Studios intro:[\s\S]*?\n\(function\(\)\{\n)([\s\S]*?)\n\}\)\(\);\n<\/script>/, 'script');
let code = body[2]
  .replace(/\n var LOGO='[^']*';/, '')
  .replace(/\n var BOOT_SND='[^']*';/, '');
// The only Gaffer-specific lines: its own Stripe return (?session_id=) skips the intro like Tier One's ?purchase=, and
// The Gaffer has no sound switch, so the Tier One save is not read.
const skipT1 = " if(/[?&]purchase=/.test(location.search)||/^#(privacy|terms|contact)$/.test(location.hash)){ b.remove(); window.__bootDone=true; return; }";
const soundT1 = " var soundOn=true; try{ var sv=JSON.parse(localStorage.getItem('tierone_v1')||'{}'); if(sv.settings&&sv.settings.sound===false) soundOn=false; }catch(e){}";
if (!code.includes(skipT1) || !code.includes(soundT1)) throw new Error('Tier One intro: script changed, review the port');
code = code.replace(skipT1, " if(/[?&]session_id=/.test(location.search)){ b.remove(); window.__bootDone=true; return; }")
  .replace(soundT1, ' var soundOn=true;');
writeFileSync(resolve(out, 'intro.ts'),
  '// @ts-nocheck -- verbatim port of Tier One\'s intro script (plain ES5); generated by scripts/extract-semba-intro.mjs.\n' +
  body[1].replace('(function(){\n', '') +
  'import { LOGO, BOOT_SND } from \'./assets\';\n\n' +
  `export const BOOT_MARKUP = ${JSON.stringify(markup)};\n\n` +
  '// Runs the intro once on the #boot element (index.html); fires "sembaboot" on window when it starts to fade out.\n' +
  'export function playIntro(){\n' + code + '\n}\n');
console.log(`logo ${logo.length} chars, sound ${snd.length} chars, css ${css.length} rules, script ${code.length} chars`);
